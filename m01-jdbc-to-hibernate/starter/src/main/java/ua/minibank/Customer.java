package ua.minibank;

// Анотації JPA лежать у пакеті jakarta.persistence.
// IDEA додасть import сама: напиши анотацію, став на неї курсор і натисни Alt+Enter → Import class.

/**
 * Клієнт банку.
 *
 * Зараз це звичайний Java-клас: Hibernate про нього нічого не знає.
 * Завдання 1 — «пояснити» Hibernate, як цей клас лежить у таблиці customers.
 * Таблицю вже створює JdbcCustomerDao.createTableIfNotExists(); ось як поля мають відповідати колонкам:
 *
 *   Поле Java           Колонка в таблиці customers
 *   ---------------     ---------------------------------------------------------------
 *   Long id         →   id          bigint, первинний ключ, значення генерує база
 *   String firstName →  first_name  varchar, NOT NULL
 *   String lastName  →  last_name   varchar, NOT NULL
 *   String email    →   email       varchar, NOT NULL, UNIQUE (два клієнти не можуть мати один email)
 *
 * Робимо по кроках 1.1 → 1.5. Після всіх кроків і завдання 2 (persistence.xml) запусти HibernateDemo.
 */
// TODO 1.1 Познач клас анотацією @Entity — «об'єкти цього класу зберігаються в базі»
// TODO 1.2 Додай @Table(name = "customers") — без неї Hibernate назве таблицю як клас: customer
public class Customer {

    // TODO 1.3 Над полем id: @Id і @GeneratedValue(strategy = GenerationType.IDENTITY)
    //      @Id — це первинний ключ таблиці.
    //      @GeneratedValue(IDENTITY) — значення id видає сама база під час INSERT.
    //      У JdbcCustomerDao це рядок "id bigint generated by default as identity primary key".
    private Long id;

    // TODO 1.4 Над трьома полями додай @Column з назвою колонки і обмеженнями (готові рядки нижче)
    //      firstName:  @Column(name = "first_name", nullable = false)
    //      lastName:   @Column(name = "last_name", nullable = false)
    //      email:      @Column(name = "email", nullable = false, unique = true)
    //
    //      name     — як називається колонка в таблиці (у Java camelCase, у SQL snake_case).
    //      nullable = false — колонка NOT NULL.
    //      unique = true    — UNIQUE.
    //      Уважно з name: якщо дві анотації вкажуть ту саму колонку, Hibernate впаде при старті
    //      з помилкою "Column 'last_name' is duplicated".
    private String firstName;
    private String lastName;
    private String email;

    // TODO 1.5 Додай конструктор без аргументів: protected Customer() { }
    //      Навіщо: коли Hibernate читає рядок з бази, він спочатку створює ПОРОЖНІЙ об'єкт
    //      через цей конструктор, а потім заповнює поля значеннями з колонок.
    //      protected, а не public — щоб у звичайному коді ним випадково не користувались.

    public Customer(String firstName, String lastName, String email) {
        this.firstName = firstName;
        this.lastName = lastName;
        this.email = email;
    }

    public Long getId() {
        return id;
    }

    /** Потрібен лише JdbcCustomerDao. Hibernate встановлює id сам. */
    public void setId(Long id) {
        this.id = id;
    }

    public String getFirstName() {
        return firstName;
    }

    public void setFirstName(String firstName) {
        this.firstName = firstName;
    }

    public String getLastName() {
        return lastName;
    }

    public void setLastName(String lastName) {
        this.lastName = lastName;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    @Override
    public String toString() {
        return "Customer{id=" + id + ", name='" + firstName + " " + lastName + "', email='" + email + "'}";
    }
}
